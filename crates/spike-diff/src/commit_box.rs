#[cfg(test)]
mod tests {
    use super::word_range;

    #[test]
    fn double_click_word_ranges() {
        let text = "fix(diff): handle CRLF_endings 漢字テスト";
        let at = |needle: &str| text.find(needle).unwrap();
        let word = |i: usize| &text[word_range(text, i)];
        assert_eq!(word(0), "fix");
        assert_eq!(word(at("ndle")), "handle");
        assert_eq!(word(at("LF_")), "CRLF_endings");
        assert_eq!(word(at("(")), "(");
        assert_eq!(word(at("字")), "漢字テスト");
        assert_eq!(
            word(text.len()),
            "漢字テスト",
            "end of text picks the last word"
        );
        assert_eq!(word_range("", 0), 0..0);
    }
}
