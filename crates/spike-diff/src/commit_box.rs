//! A single-line commit message box for the Phase 0 text-input check
//! (`spike-diff --commit-box`): IME composition, selection and clipboard.
//!
//! Adapted from GPUI's `examples/input.rs` at the pinned revision (Apache-2.0,
//! like this project). Changes: dark tokens, Ctrl shortcuts for Windows,
//! double-click word selection, Shift+Home/End, a status line, and char
//! boundaries instead of the `unicode-segmentation` crate (so combining marks
//! and emoji sequences move one code point at a time; fine for a spike).

use std::ops::Range;

use gpui::{
    App, Bounds, ClipboardItem, Context, CursorStyle, ElementId, ElementInputHandler, Entity,
    EntityInputHandler, FocusHandle, Focusable, GlobalElementId, KeyBinding, LayoutId, MouseButton,
    MouseDownEvent, MouseMoveEvent, MouseUpEvent, PaintQuad, Pixels, Point, ShapedLine,
    SharedString, Style, TextRun, UTF16Selection, UnderlineStyle, Window, actions, div, fill,
    point, prelude::*, px, relative, rgb, rgba, size,
};

actions!(
    commit_box,
    [
        Backspace,
        Delete,
        Left,
        Right,
        SelectLeft,
        SelectRight,
        SelectAll,
        Home,
        End,
        SelectHome,
        SelectEnd,
        Paste,
        Cut,
        Copy,
    ]
);

mod color {
    pub const BG_APP: u32 = 0x0e0f11;
    pub const BG_PANEL: u32 = 0x15161a;
    pub const LINE_CONTROL: u32 = 0x686d77;
    pub const INK: u32 = 0xeceef1;
    pub const INK_MUTED: u32 = 0xa0a4ac;
    pub const INK_FAINT: u32 = 0x8a8f98;
    pub const ACCENT: u32 = 0x8b95fa;
    /// `accent-soft` would be the token for selection; the spike uses accent
    /// at low alpha so ink stays readable.
    pub const SELECTION: u32 = 0x8b95fa55;
}

